function buildHtmlStarter(title: string, cssFile: string, bodyHint: string, scripts: string[]): string {
  const scriptTags = scripts.map((s) => `  <script src="${s}"></script>`).join('\n');
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${title} — Patient Tracker</title>
  <link rel="stylesheet" href="${cssFile}" />
</head>
<body>
  <div id="navbarRoot"></div>

  <main class="pt-container">
    <div class="pt-page-header">
      <div>
        <h1 class="pt-page-title">${title}</h1>
        <p class="pt-page-subtitle">${bodyHint}</p>
      </div>
    </div>

    <div id="alertBox" class="pt-alert" style="display:none;"></div>

    <section class="pt-card">
      <!-- TODO: Build your HTML form/table elements here -->
      <p style="color:#64748b;">Implement ${title} using getData() and saveData() from shared/storage.js.</p>
    </section>
  </main>

${scriptTags}
</body>
</html>
`;
}

